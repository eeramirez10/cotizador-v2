export const getLocalProductTechnicalOptions = (
  family: string | null | undefined,
  field: string,
): ProductCatalogOption[] => {
  if (field === "STANDARD") return family ? STANDARD_BY_FAMILY[family] || [] : [];
  if (field === "GRADE") return family ? GRADE_BY_FAMILY[family] || [] : [];
  return (family ? TECHNICAL_OPTIONS_BY_FAMILY[family]?.[field] : undefined)
    || COMMON_FIELD_OPTIONS[field]
    || [];
};

export const getLocalProductBrandOptions = (
  family: string | null | undefined,
): ProductCatalogOption[] => (family ? LOCAL_PRODUCT_BRANDS[family] || [] : []);
